export const dict: Record<Lang, Dict> = { ru: typeset(ru), en: typeset(en), zh: typeset(zh), fa: typeset(fa), tr: typeset(tr) };

/** The languages of the menu in the top bar, in order. */
export const langs: readonly Lang[] = ["en", "ru", "zh", "fa", "tr"];
/** Each language in its own words: the rows of the menu. */
export const langNames: Record<Lang, string> = { ru: "Русский", en: "English", zh: "简体中文", fa: "فارسی", tr: "Türkçe" };
export const langShort: Record<Lang, string> = { ru: "RU", en: "EN", zh: "中文", fa: "FA", tr: "TR" };
export const isLang = (v: unknown): v is Lang => langs.includes(v as Lang);
/** The value of the `lang` attribute (<html>, the language buttons). */
export const htmlLang = (lang: Lang): string => (lang === "zh" ? "zh-CN" : lang);
/** The direction of the page (<html dir>): Persian is read right to left. */
export const dirOf = (lang: Lang): "rtl" | "ltr" => (lang === "fa" ? "rtl" : "ltr");
/**
 * The Intl locale of a language. Persian: the Persian calendar the people read dates in, with Latin digits, the ones the apps
 * show and people compare and copy (traffic, versions, the slots), so one kind of digit on the whole page.
 */
export const localeOf = (lang: Lang): string => ({ ru: "ru", en: "en-GB", zh: "zh-CN", fa: "fa-u-nu-latn", tr: "tr" })[lang];
