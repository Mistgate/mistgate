// Persian is read right to left. A name from data (a device, an app, the brand, a DNS preset) goes into a sentence isolated, so a
// Latin name, or one that ends in a bracket or a quote, keeps its own order and never drags the words around it: one with a
// Persian letter right to left even when it starts with a Latin word ("AdGuard: بدون تبلیغات", RLI…PDI), any other in the
// direction of its first letter (FSI…PDI). A number with a Latin unit is one left-to-right piece (LRI…PDI). The marks are
// invisible. The steps point the way the line reads: «←». The tone is the polite «شما» of the Russian page; the apps keep their
// Latin names; digits are Latin (localeOf), the dates are in the Persian calendar.
