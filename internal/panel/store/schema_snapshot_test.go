const snapshotPath = "schema_snapshot.sql"

const snapshotUpdateCmd = "go test ./internal/panel/store -run '^TestSchemaSnapshot$' -update"

var (
	snapshotVersionLine = regexp.MustCompile(`(?m)^-- goose version (\d+)$`)
	snapshotDateTime    = regexp.MustCompile(`^'(\d{4}-\d\d-\d\d \d\d:\d\d:\d\d)'$`)
)

// nowWindow is the span of Unix seconds in which a migration ran. A time value inside it is "now" of that run: the snapshot
// writes it as the SQL that makes it, and the comparison of two databases treats it as equal to any other "now".
type nowWindow struct{ lo, hi int64 }

// around returns the window from slack seconds before start to slack seconds after the present.
func around(start time.Time) nowWindow {
	return nowWindow{lo: start.Unix() - 2, hi: time.Now().Unix() + 2}
}

// expr is the SQL for the quoted value lit when it lies in the window.
func (w nowWindow) expr(lit string) (string, bool) {
	if n, err := strconv.ParseInt(lit, 10, 64); err == nil {
		return "strftime('%s','now')", n >= w.lo && n <= w.hi
	}
	if m := snapshotDateTime.FindStringSubmatch(lit); m != nil {
		if at, err := time.Parse(time.DateTime, m[1]); err == nil {
			return "datetime('now')", at.Unix() >= w.lo && at.Unix() <= w.hi
		}
	}
	return "", false
}

func quoteIdent(name string) string { return `"` + strings.ReplaceAll(name, `"`, `""`) + `"` }

// tableRows returns the columns of table (the generated ones left out) and its rows, every value as a SQL literal.
func tableRows(ctx context.Context, db *sql.DB, table string) (cols []string, rows [][]string, err error) {
	cr, err := db.QueryContext(ctx, `SELECT name FROM pragma_table_info(?) ORDER BY cid`, table)
	if err != nil {
		return nil, nil, err
	}
	for cr.Next() {
		var c string
		if err := cr.Scan(&c); err != nil {
			cr.Close()
			return nil, nil, err
		}
		cols = append(cols, c)
	}
	cr.Close()
	if err := cr.Err(); err != nil {
		return nil, nil, err
	}
	quoted := make([]string, len(cols))
	order := make([]string, len(cols))
	for i, c := range cols {
		quoted[i] = "quote(" + quoteIdent(c) + ")"
		order[i] = quoteIdent(c)
	}
	rr, err := db.QueryContext(ctx, "SELECT "+strings.Join(quoted, ",")+" FROM "+quoteIdent(table)+" ORDER BY "+strings.Join(order, ","))
	if err != nil {
		return nil, nil, err
	}
	defer rr.Close()
	for rr.Next() {
		row := make([]string, len(cols))
		ptrs := make([]any, len(cols))
		for i := range row {
			ptrs[i] = &row[i]
		}
		if err := rr.Scan(ptrs...); err != nil {
			return nil, nil, err
		}
		rows = append(rows, row)
	}
	return cols, rows, rr.Err()
}

func queryStrings(ctx context.Context, db *sql.DB, q string) ([]string, error) {
	rows, err := db.QueryContext(ctx, q)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []string
	for rows.Next() {
		var s string
		if err := rows.Scan(&s); err != nil {
			return nil, err
		}
		out = append(out, s)
	}
	return out, rows.Err()
}

// snapshotSQL is the script that builds the schema and the data of db. It is what schema_snapshot.sql holds for the database
// that the full migration chain makes.
func snapshotSQL(ctx context.Context, db *sql.DB, win nowWindow) (string, error) {
	var version int64
	if err := db.QueryRowContext(ctx, `SELECT coalesce(max(version_id), 0) FROM goose_db_version`).Scan(&version); err != nil {
		return "", err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "-- Schema and data of a new, fully migrated panel database.\n")
	fmt.Fprintf(&b, "-- goose version %d\n", version)
	fmt.Fprintf(&b, "-- Generated by `%s`; do not edit by hand.\n", snapshotUpdateCmd)
	b.WriteString("PRAGMA defer_foreign_keys = ON;\n")
	objects, err := db.QueryContext(ctx, `SELECT sql FROM sqlite_master
		WHERE sql IS NOT NULL AND substr(name, 1, 7) <> 'sqlite_'
		ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 ELSE 3 END, name`)
	if err != nil {
		return "", err
	}
	for objects.Next() {
		var s string
		if err := objects.Scan(&s); err != nil {
			objects.Close()
			return "", err
		}
		b.WriteString(s + ";\n")
	}
	objects.Close()
	if err := objects.Err(); err != nil {
		return "", err
	}
	tables, err := queryStrings(ctx, db, `SELECT name FROM sqlite_master WHERE type = 'table' AND substr(name, 1, 7) <> 'sqlite_' ORDER BY name`)
	if err != nil {
		return "", err
	}
	insert := func(table string) error {
		cols, rows, err := tableRows(ctx, db, table)
		if err != nil {
			return fmt.Errorf("%s: %w", table, err)
		}
		names := make([]string, len(cols))
		for i, c := range cols {
			names[i] = quoteIdent(c)
		}
		for _, row := range rows {
			for i, v := range row {
				if e, ok := win.expr(v); ok {
					row[i] = e
				}
			}
			fmt.Fprintf(&b, "INSERT INTO %s (%s) VALUES (%s);\n", quoteIdent(table), strings.Join(names, ", "), strings.Join(row, ", "))
		}
		return nil
	}
	for _, t := range tables {
		if err := insert(t); err != nil {
			return "", err
		}
	}
	// AUTOINCREMENT counters, the rows of empty tables included: the inserts above moved them.
	b.WriteString("DELETE FROM sqlite_sequence;\n")
	if err := insert("sqlite_sequence"); err != nil {
		return "", err
	}
	return b.String(), nil
}

// dumpDB lists the whole content of db for comparison: every sqlite_master row with its exact text, every row of every table
// (sqlite_sequence and goose_db_version included) as quoted values, "now" values replaced by NOW, sorted.
func dumpDB(ctx context.Context, db *sql.DB, win nowWindow) ([]string, error) {
	out, err := queryStrings(ctx, db, `SELECT 'master|' || type || '|' || name || '|' || tbl_name || '|' || coalesce(sql, '') FROM sqlite_master`)
	if err != nil {
		return nil, err
	}
	tables, err := queryStrings(ctx, db, `SELECT name FROM sqlite_master WHERE type = 'table'`)
	if err != nil {
		return nil, err
	}
	for _, t := range tables {
		_, rows, err := tableRows(ctx, db, t)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", t, err)
		}
		for _, row := range rows {
			for i, v := range row {
				if _, ok := win.expr(v); ok {
					row[i] = "NOW"
				}
			}
			out = append(out, "row|"+t+"|"+strings.Join(row, "|"))
		}
	}
	sort.Strings(out)
	return out, nil
}

func clip(s string) string {
	if len(s) > 300 {
		return s[:300] + "..."
	}
	return s
}

// diffDumps is "" when a and b are the same, else the first line where they differ.
func diffDumps(a, b []string) string {
	for i := 0; i < max(len(a), len(b)); i++ {
		var x, y string
		if i < len(a) {
			x = a[i]
		}
		if i < len(b) {
			y = b[i]
		}
		if x != y {
			return fmt.Sprintf("first difference (line %d of %d and %d):\n  goose:    %s\n  snapshot: %s", i, len(a), len(b), clip(x), clip(y))
		}
	}
	return ""
}

func openBare(t *testing.T, path string) *Store {
	t.Helper()
	w, err := openDB(path, 1, false)
	if err != nil {
		t.Fatal(err)
	}
	r, err := openDB(path, 4, true)
	if err != nil {
		t.Fatal(err)
	}
	s := &Store{W: w, R: r}
	t.Cleanup(func() { s.Close() })
	return s
}

// gooseDB is a database the migration chain alone made, and the second it started at.
func gooseDB(t *testing.T) (*Store, time.Time) {
	t.Helper()
	start := time.Now()
	s, p := openProvider(t)
	if _, err := p.Up(context.Background()); err != nil {
		t.Fatal(err)
	}
	return s, start
}

func lastMigrations(t *testing.T, p *goose.Provider) (last, before int64) {
	t.Helper()
	src := p.ListSources()
	if len(src) < 2 {
		t.Fatal("fewer than two migrations")
	}
	return src[len(src)-1].Version, src[len(src)-2].Version
}

func TestSchemaSnapshot(t *testing.T) {
	ctx := context.Background()
	ref, start := gooseDB(t)
	got, err := snapshotSQL(ctx, ref.W, around(start))
	if err != nil {
		t.Fatal(err)
	}
	if *updateSchemaGolden {
		if err := os.WriteFile(snapshotPath, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Skipf("%s rewritten; run the test again without -update", snapshotPath)
	}
	want, err := os.ReadFile(snapshotPath)
	if err != nil {
		t.Fatalf("read the schema snapshot (run %s): %v", snapshotUpdateCmd, err)
	}
	if string(want) != got {
		var inFile int64 = -1
		if m := snapshotVersionLine.FindSubmatch(want); m != nil {
			inFile, _ = strconv.ParseInt(string(m[1]), 10, 64)
		}
		var newest int64
		_ = ref.W.QueryRowContext(ctx, `SELECT max(version_id) FROM goose_db_version`).Scan(&newest)
		t.Fatalf("%s is not what the migrations make (it is at goose version %d, the newest migration is %d); run %s",
			snapshotPath, inFile, newest, snapshotUpdateCmd)
	}

	// The database the real path builds: the snapshot, then goose.
	s := openBare(t, filepath.Join(t.TempDir(), "snap.db"))
	applied, err := s.applySnapshot(ctx, schemaSnapshotSQL)
	if err != nil || !applied {
		t.Fatalf("applySnapshot on an empty database = %v, %v", applied, err)
	}
	if err := s.migrate(ctx); err != nil {
		t.Fatal(err)
	}
	win := around(start)
	assertSameAsGoose(t, ref, s, win)

	var v int64
	var integrity string
	if err := s.W.QueryRowContext(ctx, `PRAGMA user_version`).Scan(&v); err != nil {
		t.Fatal(err)
	}
	var refV int64
	if err := ref.W.QueryRowContext(ctx, `PRAGMA user_version`).Scan(&refV); err != nil {
		t.Fatal(err)
	}
	if v != refV {
		t.Errorf("user_version = %d, goose database has %d", v, refV)
	}
	if err := s.W.QueryRowContext(ctx, `PRAGMA integrity_check`).Scan(&integrity); err != nil || integrity != "ok" {
		t.Errorf("integrity_check = %q, %v", integrity, err)
	}
	fk, err := queryStrings(ctx, s.W, `SELECT "table" || '|' || rowid FROM pragma_foreign_key_check`)
	if err != nil || len(fk) != 0 {
		t.Errorf("foreign_key_check = %v, %v", fk, err)
	}
}

func assertSameAsGoose(t *testing.T, ref, other *Store, win nowWindow) {
	t.Helper()
	ctx := context.Background()
	a, err := dumpDB(ctx, ref.W, win)
	if err != nil {
		t.Fatal(err)
	}
	b, err := dumpDB(ctx, other.W, win)
	if err != nil {
		t.Fatal(err)
	}
	if d := diffDumps(a, b); d != "" {
		t.Fatalf("the database differs from the goose one. %s\nData the migrations make must be deterministic to live in the snapshot: a random value or a time that is not \"now\" cannot; make it deterministic or fill it in Go after Open.", d)
	}
}

// A snapshot of an older schema is brought up to date by goose.
func TestSchemaSnapshotStaleIsCaughtUp(t *testing.T) {
	ctx := context.Background()
	start := time.Now()
	ref, _ := gooseDB(t)

	old, p := openProvider(t)
	last, before := lastMigrations(t, p)
	if _, err := p.UpTo(ctx, before); err != nil {
		t.Fatal(err)
	}
	stale, err := snapshotSQL(ctx, old.W, around(start))
	if err != nil {
		t.Fatal(err)
	}

	s := openBare(t, filepath.Join(t.TempDir(), "stale.db"))
	if applied, err := s.applySnapshot(ctx, stale); err != nil || !applied {
		t.Fatalf("applySnapshot = %v, %v", applied, err)
	}
	var v int64
	if err := s.W.QueryRowContext(ctx, `SELECT max(version_id) FROM goose_db_version`).Scan(&v); err != nil || v != before {
		t.Fatalf("stale snapshot is at version %d (%v), want %d", v, err, before)
	}
	if err := s.migrate(ctx); err != nil {
		t.Fatal(err)
	}
	if err := s.W.QueryRowContext(ctx, `SELECT max(version_id) FROM goose_db_version`).Scan(&v); err != nil || v != last {
		t.Fatalf("after migrate version = %d (%v), want %d", v, err, last)
	}
	assertSameAsGoose(t, ref, s, around(start))
}

// A database that has migrations applied is left to goose: the snapshot is not put over it.
func TestOpenSkipsSnapshotOnStartedDatabase(t *testing.T) {
	ctx := context.Background()
	start := time.Now()
	ref, _ := gooseDB(t)

	path := filepath.Join(t.TempDir(), "mid.db")
	s := openBare(t, path)
	sub, err := fs.Sub(migrationsFS, "migrations")
	if err != nil {
		t.Fatal(err)
	}
	mp, err := goose.NewProvider(goose.DialectSQLite3, s.W, sub)
	if err != nil {
		t.Fatal(err)
	}
	src := mp.ListSources()
	if _, err := mp.UpTo(ctx, src[len(src)/2].Version); err != nil {
		t.Fatal(err)
	}
	if applied, err := s.applySnapshot(ctx, schemaSnapshotSQL); err != nil || applied {
		t.Fatalf("applySnapshot on a migrated database = %v, %v", applied, err)
	}
	if err := s.Close(); err != nil {
		t.Fatal(err)
	}

	st, err := Open(ctx, path)
	if err != nil {
		t.Fatal(err)
	}
	defer st.Close()
	assertSameAsGoose(t, ref, st, around(start))
}

func TestOpenConcurrentNewFile(t *testing.T) {
	ctx := context.Background()
	start := time.Now()
	ref, _ := gooseDB(t)

	// Both processes switching a new file to WAL at once is a race older than the snapshot (SQLITE_BUSY in openDB, before
	// any schema work); the file starts in WAL mode, empty, so that what is raced here is who builds the schema.
	path := filepath.Join(t.TempDir(), "new.db")
	pre, err := openDB(path, 1, false)
	if err != nil {
		t.Fatal(err)
	}
	if err := pre.Close(); err != nil {
		t.Fatal(err)
	}
	stores := make([]*Store, 2)
	errs := make([]error, 2)
	var wg sync.WaitGroup
	for i := range stores {
		wg.Add(1)
		go func() {
			defer wg.Done()
			stores[i], errs[i] = Open(ctx, path)
		}()
	}
	wg.Wait()
	for i := range stores {
		if errs[i] != nil {
			t.Fatalf("Open %d: %v", i, errs[i])
		}
		defer stores[i].Close()
	}
	assertSameAsGoose(t, ref, stores[0], around(start))
}

