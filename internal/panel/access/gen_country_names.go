//go:build ignore

// gen_country_names writes country_names.go: the names golang.org/x/text gives to the two-letter codes a node can carry,
// in the three languages of the panel. Run it from this directory (go generate) after golang.org/x/text changes;
// TestCountryNamesAreTheLibrarys fails until you do.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"

	"golang.org/x/text/language"
	"golang.org/x/text/language/display"
)

func main() {
	var out bytes.Buffer
	out.WriteString("// Code generated by gen_country_names.go; DO NOT EDIT.\n\npackage access\n\n")
	out.WriteString("// countryNames are the names golang.org/x/text/language/display gives to the two-letter codes that name a country,\n")
	out.WriteString("// sorted by code. A language the library has no name in is empty here. They are data, not the library, because\n")
	out.WriteString("// the library's tables for every language of the world are 2.5 MB of the edge edition's wasm.\n")
	out.WriteString("var countryNames = [...]countryNameRow{\n")
	for a := 'A'; a <= 'Z'; a++ {
		for b := 'A'; b <= 'Z'; b++ {
			code := string([]rune{a, b})
			r, err := language.ParseRegion(code)
			if err != nil || !r.IsCountry() {
				continue
			}
			names := make([]string, 0, 3)
			for _, lang := range []string{"en", "ru", "zh"} {
				names = append(names, display.Regions(language.Make(lang)).Name(r))
			}
			fmt.Fprintf(&out, "\t{%q, %q, %q, %q},\n", code, names[0], names[1], names[2])
		}
	}
	out.WriteString("}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("country_names.go", []byte(strings.ReplaceAll(string(src), "\r\n", "\n")), 0o644); err != nil {
		log.Fatal(err)
	}
}
